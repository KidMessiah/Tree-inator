"""Bake one small picture per colour theme, rendered on the same generic layout, for the theme cards in the app.
Writes crates/tree-inator/assets/themes/<slug>.png and a Rust list of them.
"""
import os, re, subprocess
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
CLI = os.path.join(ROOT, "target", "release", "forest-cli.exe")
OUT = os.path.join(ROOT, "crates", "tree-inator", "assets", "themes")
os.makedirs(OUT, exist_ok=True)
src = open(os.path.join(ROOT, "crates", "forest-core", "src", "params.rs"), encoding="utf-8").read()
names = re.findall(r'Theme \{\s*name: "([^"]+)",\s*note:', src)
import json
names += list(json.load(open(os.path.join(ROOT, "crates", "forest-core", "assets", "satellite_themes.json"), encoding="utf-8")))
print(len(names), "themes")
tmp = os.environ.get("TEMP", ".")
entries = []
for n in names:
    slug = re.sub(r"[^a-z0-9]+", "_", n.lower()).strip("_")
    if os.path.exists(os.path.join(OUT, slug + ".png")) and not os.environ.get("FORCE"):
        entries.append((n, slug))
        continue
    png = os.path.join(tmp, f"card_{slug}.png")
    subprocess.run([CLI, "-theme", n, "-bg", "-scale", "0.5", "-out", png], check=True, capture_output=True)
    im = Image.open(png).convert("RGB")
    w, h = im.size
    # the middle of the forest, in the card's shape
    cw, ch = int(w * 0.5), int(h * 0.5)
    im = im.crop(((w - cw) // 2, (h - ch) // 2, (w + cw) // 2, (h + ch) // 2)).resize((192, 120), Image.LANCZOS)
    im.save(os.path.join(OUT, slug + ".png"), optimize=True)
    entries.append((n, slug))
    print(n, flush=True)
lines = ["// Generated by tools/bake_theme_cards.py. Do not edit.", "pub const CARDS: &[(&str, &[u8])] = &["]
for n, slug in entries:
    lines.append(f'    ("{n}", include_bytes!("../../assets/themes/{slug}.png")),')
lines.append("];")
open(os.path.join(ROOT, "crates", "tree-inator", "src", "app", "theme_cards.rs"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
