"""Write crates/forest-core/src/treegen_data.rs from friggog/tree-gen's presets and leaf shapes.

Run from anywhere. The data is the author's (GPL-3.0, see research/third_party/tree-gen/LICENSE).
"""
import importlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TP = os.path.join(HERE, "..", "third_party", "tree-gen")
sys.path.insert(0, os.path.join(TP, "shims"))
sys.path.insert(0, TP)

from treegen.parametric.tree_params.tree_param import TreeParam  # noqa: E402
from treegen import leaf_shapes as ls  # noqa: E402

NAMES = ("acer apple balsam_fir bamboo black_oak black_tupelo cambridge_oak douglas_fir european_larch fan_palm "
         "hill_cherry lombardy_poplar palm quaking_aspen sassafras silver_birch small_pine sphere_tree "
         "weeping_willow weeping_willow_o").split()

ARR4 = ["base_size", "down_angle", "down_angle_v", "rotate", "rotate_v", "branches", "length", "length_v", "taper",
        "seg_splits", "split_angle", "split_angle_v", "curve_res", "curve", "curve_back", "curve_v", "bend_v",
        "branch_dist", "radius_mod"]
SCALARS = ["shape", "g_scale", "g_scale_v", "levels", "ratio", "ratio_power", "flare", "base_splits", "leaf_blos_num",
           "leaf_shape", "leaf_scale", "leaf_scale_x", "leaf_bend", "blossom_shape", "blossom_scale", "blossom_rate",
           "prune_ratio", "prune_width", "prune_width_peak", "prune_power_low", "prune_power_high"]


def f(v):
    return repr(float(v)) if float(v) != int(float(v)) else "%d.0" % int(float(v))


def main():
    out = ["//! Parameter sets and leaf shapes from friggog/tree-gen (Chris Hewitt), GPL-3.0.",
           "//! Generated by research/scripts/emit_treegen_data.py. Do not edit by hand.", "",
           "#[derive(Clone, Copy, Debug)]", "pub struct Preset {", "    pub name: &'static str,"]
    for s in SCALARS:
        out.append(f"    pub {s}: f64,")
    for a in ARR4:
        out.append(f"    pub {a}: [f64; 4],")
    out += ["    pub tropism: [f64; 3],", "}", "", "pub const PRESETS: &[Preset] = &["]
    for n in NAMES:
        p = importlib.import_module("treegen.parametric.tree_params." + n).params
        t = TreeParam(p)
        out.append("    Preset {")
        out.append(f'        name: "{n}",')
        for s in SCALARS:
            out.append(f"        {s}: {f(getattr(t, s))},")
        for a in ARR4:
            vals = list(getattr(t, a))
            if len(vals) != 4:
                raise SystemExit(f"{n}.{a} has {len(vals)} entries")
            out.append(f"        {a}: [{', '.join(f(v) for v in vals)}],")
        out.append(f"        tropism: [{', '.join(f(v) for v in t.tropism)}],")
        out.append("    },")
    out.append("];")
    out.append("")
    out.append("/// (vertices, faces) for leaf shapes 1 to 10, then blossom shapes 1 to 3.")
    out.append("pub type Shape = (&'static [[f64; 3]], &'static [&'static [usize]]);")
    out.append("")

    def shape_src(sh):
        v = ", ".join("[%s, %s, %s]" % tuple(f(c) for c in vert) for vert in sh[0])
        fs = ", ".join("&[" + ", ".join(str(i) for i in face) + "]" for face in sh[1])
        return f"(&[{v}], &[{fs}])"

    out.append("pub const LEAF_SHAPES: [Shape; 10] = [")
    for i in range(10):
        out.append("    " + shape_src(ls.leaves(i)) + ",")
    out.append("];")
    out.append("")
    out.append("pub const BLOSSOM_SHAPES: [Shape; 3] = [")
    for i in range(3):
        out.append("    " + shape_src(ls.blossom(i)) + ",")
    out.append("];")
    dst = os.path.join(HERE, "..", "..", "crates", "forest-core", "src", "treegen_data.rs")
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(dst), len(NAMES), "presets")


main()
